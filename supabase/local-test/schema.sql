-- RPCs the app calls (bodies inferred from how the app uses them).
create or replace function public.delete_chat_record(p_id integer) returns void
language sql security definer set search_path = public as $$
  delete from public.chat_records where id = p_id;
$$;
create or replace function public.delete_tracker_user(p_user_id text) returns void
language sql security definer set search_path = public as $$
  delete from public.tracker_users where user_id = p_user_id;
$$;
create or replace function public.merge_dismissed_notifs(p_map jsonb) returns void
language plpgsql security definer set search_path = public as $$
declare k text; v jsonb;
begin
  for k, v in select * from jsonb_each(coalesce(p_map, '{}'::jsonb)) loop
    insert into public.dismissed_notifs (user_key, notif_ids)
    values (k, coalesce(v, '[]'::jsonb))
    on conflict (user_key) do update set notif_ids = (
      select coalesce(jsonb_agg(distinct x), '[]'::jsonb)
      from jsonb_array_elements(public.dismissed_notifs.notif_ids || excluded.notif_ids) as x
    );
  end loop;
end;
$$;
create or replace function public.reset_chat_records_id_sequence() returns void
language sql security definer set search_path = public as $$
  select setval(pg_get_serial_sequence('public.chat_records','id'),
                coalesce((select max(id) from public.chat_records), 0) + 1, false);
$$;

