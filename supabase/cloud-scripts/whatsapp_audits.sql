-- Safe to run more than once. Does not touch any existing table.
create table if not exists public.whatsapp_audits (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- Who logged it (tracker_users.user_id, plus name / email like chat_records.analyst).
  created_by_user_id text not null default '',
  analyst text not null default '',
  analyst_email text not null default '',
  updated_by text,
  -- Sheet columns. "Day" is derived from audit_date in the app, not stored.
  audit_date date not null,
  shift text not null default '',
  team text not null default '',
  profile text not null default '',
  client_name text not null,
  -- Clock times stored as HH:MM:SS text, same as chat_records.first_receive / first_reply.
  client_msg_received text not null default '',
  reply_time text not null default '',
  category text,
  client_message text not null default '',
  constraint whatsapp_audits_category_check check (
    category is null
    or category in ('same_day', 'next_morning', 'after_12pm_next_day', 'main_cases', 'sunday_only', 'left_as_seen')
  ),
  constraint whatsapp_audits_client_name_check check (char_length(btrim(client_name)) between 1 and 200),
  constraint whatsapp_audits_shift_check check (char_length(shift) <= 40),
  constraint whatsapp_audits_client_message_check check (char_length(client_message) <= 2000)
);

create index if not exists whatsapp_audits_date_id_idx on public.whatsapp_audits (audit_date desc, id desc);
create index if not exists whatsapp_audits_team_idx on public.whatsapp_audits (team);
create index if not exists whatsapp_audits_creator_idx on public.whatsapp_audits (created_by_user_id);

comment on table public.whatsapp_audits is
  'WhatsApp Audit entries (separate from chat_records). Written by the app server with the service role.';

-- Same model as chat_records: RLS on with no policies, so only the server
-- (service role) can read or write. Browsers never query this table directly.
alter table public.whatsapp_audits enable row level security;
grant select, insert, update, delete on table public.whatsapp_audits to service_role;
grant usage, select on sequence public.whatsapp_audits_id_seq to service_role;

