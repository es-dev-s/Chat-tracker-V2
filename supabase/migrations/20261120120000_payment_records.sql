-- Payment Records: its own dataset, separate from chat_records.
-- Chat analysts add records (add-only). The main team lead adds, edits and deletes.
-- Chat analyst team leads view records added by analysts.
-- Safe to run more than once. Does not touch any existing table.
create table if not exists public.payment_records (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- Who added it (tracker_users.user_id) and in which role, so visibility can be scoped.
  created_by_user_id text not null default '',
  created_by_role text not null default '',
  updated_by text,
  -- Payment period.
  from_date date not null,
  to_date date not null,
  -- Amounts in AUD.
  total_amount numeric(12, 2) not null,
  initial_amount numeric(12, 2) not null,
  final_amount numeric(12, 2) not null,
  payment_count integer not null,
  team text not null,
  profile text not null,
  -- Chat analyst the payment belongs to (the "receiver").
  analyst text not null,
  constraint payment_records_dates_check check (to_date >= from_date),
  constraint payment_records_amounts_check check (
    total_amount > 0 and initial_amount >= 0 and final_amount >= 0
    and initial_amount + final_amount <= total_amount
  ),
  constraint payment_records_count_check check (payment_count between 1 and 1000),
  constraint payment_records_team_check check (char_length(btrim(team)) between 1 and 120),
  constraint payment_records_profile_check check (char_length(btrim(profile)) between 1 and 120),
  constraint payment_records_analyst_check check (char_length(btrim(analyst)) between 1 and 120)
);

create index if not exists payment_records_from_date_id_idx on public.payment_records (from_date desc, id desc);
create index if not exists payment_records_team_idx on public.payment_records (team);
create index if not exists payment_records_creator_idx on public.payment_records (created_by_user_id);

comment on table public.payment_records is
  'Payment Records (separate from chat_records). Written by the app server with the service role.';

-- Same model as chat_records: RLS on with no policies, so only the server
-- (service role) can read or write. Browsers never query this table directly.
alter table public.payment_records enable row level security;
grant select, insert, update, delete on table public.payment_records to service_role;
grant usage, select on sequence public.payment_records_id_seq to service_role;

notify pgrst, 'reload schema';
